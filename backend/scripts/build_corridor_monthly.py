"""
Builds db/03_corridor_monthly.sql: crashes per corridor per month, split into
Damage to Property / Non Fatal Injury / Fatal. This is the data behind the
12-month severity ranking on the Dashboard, Risk Areas and Map pages.

Re-run when newer MMDA files arrive (name them RAW_Data_QC_<year>.xlsx):
    python scripts/build_corridor_monthly.py "C:/path/to/folder/with/the/xlsx/files"
then run the regenerated db/03_corridor_monthly.sql in pgAdmin. Existing months are
left untouched (ON CONFLICT DO NOTHING); new months are added, and the ranking moves
forward to the newest month automatically.

Corridors come from db/02_seed_risk_areas.sql. Street names are trimmed, repeated
spaces collapsed, and direction suffixes like (NB)/(SB) merged into one corridor.
"""
import collections, glob, os, re, sys
import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
DB_DIR = os.path.join(HERE, "..", "db")
RAW_DIR = sys.argv[1] if len(sys.argv) > 1 else "."
MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]
OUTCOME = {"Damage to Property": 0, "Non Fatal Injury": 1, "Fatal": 2}

seed = open(os.path.join(DB_DIR, "02_seed_risk_areas.sql"), encoding="utf-8").read()
corridors = [c.replace("''", "'") for c in re.findall(r"VALUES \('((?:[^']|'')*)'", seed)]
wanted = set(corridors)

def corridor_name(street):
    s = re.sub(r"\s+", " ", str(street if street is not None else "Unknown").strip())
    return re.sub(r"\s*\((NB|SB|EB|WB)\)$", "", s)

counts = collections.defaultdict(lambda: [0, 0, 0])   # (corridor, "YYYY-MM-01") -> [damage, injury, fatal]
years = []
for path in sorted(glob.glob(os.path.join(RAW_DIR, "RAW_Data_QC_*.xlsx"))):
    year = int(re.search(r"(\d{4})", os.path.basename(path)).group(1))   # the file's year, as in the notebook
    years.append(year)
    # read_only + max_col: some sheets declare ~16,000 mostly-empty columns
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True)["QC road crash data"]
    idx = None
    for i, row in enumerate(ws.iter_rows(max_col=60, values_only=True)):
        if i == 0:
            idx = {h: j for j, h in enumerate(row) if h}
            continue
        month = str(row[idx["Month"]] or "").strip()[:3].lower()
        outcome = str(row[idx["Classification"]] or "").strip()
        corridor = corridor_name(row[idx["Street"]])
        if month in MONTHS and outcome in OUTCOME and corridor in wanted:
            counts[(corridor, f"{year}-{MONTHS.index(month) + 1:02d}-01")][OUTCOME[outcome]] += 1

if not years:
    sys.exit(f"No RAW_Data_QC_*.xlsx files found in {RAW_DIR!r}")

all_months = [f"{y}-{m:02d}-01" for y in sorted(years) for m in range(1, 13)]
esc = lambda s: s.replace("'", "''")
values = ",\n".join(
    f"('{esc(c)}', '{m}', {d}, {inj}, {f})"
    for c in corridors for m in all_months for d, inj, f in [counts[(c, m)]]
)
sql = f"""-- Adds monthly crash counts per corridor (the data behind the 12-month severity ranking),
-- and a logged_by_name column so staff-logged incidents can be stored in the database.
-- Safe to run more than once. Run AFTER 01 and 02, connected to qc_road_safety as postgres.
-- Source: MMDA road crash records for Quezon City, {min(years)}-{max(years)} ({len(corridors)} monitored corridors;
-- direction suffixes such as (NB)/(SB) are merged into one corridor).
-- Generated by scripts/build_corridor_monthly.py - edit that script, not this file.

CREATE TABLE IF NOT EXISTS corridor_monthly (
    corridor VARCHAR(150) NOT NULL REFERENCES risk_areas(corridor),
    month DATE NOT NULL,                         -- first day of the month
    damage INTEGER NOT NULL DEFAULT 0,           -- Damage to Property crashes
    injury INTEGER NOT NULL DEFAULT 0,           -- Non Fatal Injury crashes
    fatal INTEGER NOT NULL DEFAULT 0,            -- Fatal crashes
    PRIMARY KEY (corridor, month)
);

ALTER TABLE incidents ADD COLUMN IF NOT EXISTS logged_by_name VARCHAR(100);

GRANT ALL PRIVILEGES ON corridor_monthly TO csrp2_app;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO csrp2_app;

INSERT INTO corridor_monthly (corridor, month, damage, injury, fatal) VALUES
{values}
ON CONFLICT (corridor, month) DO NOTHING;
"""
out = os.path.join(DB_DIR, "03_corridor_monthly.sql")
with open(out, "w", encoding="utf-8") as fh:
    fh.write(sql)
total = sum(sum(v) for v in counts.values())
print(f"Wrote {out}: {len(corridors)} corridors x {len(all_months)} months, {total:,} crashes")
